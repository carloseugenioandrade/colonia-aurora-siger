# MODULE 1 — DATA STRUCTURES
# Colony data organized in dictionaries (key-value pairs) and
# lists, with hierarchy: colony → systems → subsystems
# ----------------------------------------------------------------

def inicializar_colonia(bateria=65, solar=40, eolico=20,
                         consumo=70, reserva=10,
                         vento=11, temp_interna=22, temp_externa=-60):
    """
    Creates and returns the main colony dictionary.
    Accepts parameters to make testing different scenarios easier.
    """
    colonia = {
        "nome": "Aurora Siger",
        "energia": {
            "bateria":        bateria,   # current charge level (%)
            "geracao_solar":  solar,     # units generated by solar panels
            "geracao_eolica": eolico,    # units generated by wind turbines
            "consumo_total":  consumo,   # total units consumed
            "reserva":        reserva    # units stored in reserve
        },
        "clima": {
            "temperatura_interna": temp_interna,  # degrees Celsius
            "temperatura_externa": temp_externa,  # degrees Celsius
            "velocidade_vento":    vento          # m/s
        },
        # Hierarchy: energetico    → solar / eolico
        #            suporte_vida  → oxigenio / aquecimento / agua
        #            nao_essenciais → laboratorio / comunicacao_secundaria
        "sistemas": {
            "energetico": {
                "solar":  {"ativo": True, "geracao": solar},
                "eolico": {"ativo": True, "geracao": eolico}
            },
            "suporte_vida": {
                "oxigenio":    {"ativo": True, "consumo": 20},
                "aquecimento": {"ativo": True, "consumo": 15},
                "agua":        {"ativo": True, "consumo": 10}
            },
            "nao_essenciais": {
                "laboratorio":            {"ativo": True, "consumo": 15},
                "comunicacao_secundaria": {"ativo": True, "consumo": 10}
            }
        },
        # Historical data series used for linear regression
        "historico": {
            "vento":          [6,  8,  10, 12, 14],
            "energia_eolica": [15, 20, 25, 30, 35]
        },
        # Stores every decision made during the current cycle
        "log_decisoes": []
    }
    return colonia


# ----------------------------------------------------------------
# VISUAL HELPERS — progress bar and section separators
# ----------------------------------------------------------------

def barra(valor, maximo=100, largura=20, cheio="█", vazio="░"):
    """Returns a text-based progress bar proportional to the value."""
    valor = max(0, min(valor, maximo))           # clamp to valid range
    preenchido = int((valor / maximo) * largura)
    return cheio * preenchido + vazio * (largura - preenchido)


def cabecalho(titulo):
    """Prints a bordered section header."""
    linha = "─" * 52
    print(f"\n┌{linha}┐")
    print(f"│  {titulo:<50}│")
    print(f"└{linha}┘")


def separador():
    """Prints a light dotted separator line."""
    print("  " + "·" * 48)


